const fs = require('fs'), vm = require('vm'), assert = require('assert');
const messages = [], context = { window: { arseneStartFlow: { toast: message => messages.push(message) } }, document: {}, addEventListener() {} };
for (const file of ['data', 'game']) vm.runInNewContext(fs.readFileSync(`${__dirname}/../js/${file}.js`, 'utf8'), context);
const actor = Object.create(context.window.BattleGame.prototype);
actor.profile = { currentJob: 'warrior', lastNormalJob: 'warrior', initialJob: 'mage', flags: {} };
actor.isJobUnlocked = () => true;
actor.saveProfile = () => {};
actor.switchJobState = function (id) { if (this.profile.currentJob === id) return false; this.profile.currentJob = id; if (id !== 'phantomThief') this.profile.lastNormalJob = id; return true; };
assert(actor.changeJob('phantomThief'));
assert(messages[0].includes('異世界のみ'));
assert(messages[0].includes('戦士'));
assert(actor.restoreNormalDungeonJob());
assert.strictEqual(actor.profile.currentJob, 'warrior');
assert(messages[1].includes('通常ダンジョンは《戦士》'));
assert.strictEqual(actor.restoreNormalDungeonJob(), false);
assert.strictEqual(messages.length, 2, 'normal jobs do not receive irrelevant notices');
actor.profile.currentJob = 'phantomThief'; actor.profile.otherWorldReturnJob = 'priest';
assert.strictEqual(actor.normalDungeonReturnJob(), 'priest', 'notice and restore share the same target');
actor.restoreNormalDungeonJob(true);
assert.strictEqual(messages.length, 2, 'forced return from otherworld does not announce dungeon entry');
assert.strictEqual(actor.profile.currentJob, 'priest');
const source = fs.readFileSync(`${__dirname}/../js/game.js`, 'utf8');
assert(source.includes('jobId === \'phantomThief\' ? `<p class="job-lock-notice"'), 'job details retain visible guidance');
assert(source.includes('this.profile.currentJob === \'phantomThief\' ? `<p class="job-lock-notice"'), 'normal dungeon selection warns before entry');
console.log('phantom thief guidance regression: ok');

const fs = require('fs'), vm = require('vm'), assert = require('assert');
const context = { window: {}, document: {}, addEventListener() {} };
for (const file of ['data', 'game']) vm.runInNewContext(fs.readFileSync(`${__dirname}/../js/${file}.js`, 'utf8'), context);
const actor = Object.create(context.window.BattleGame.prototype);
actor.profile = { seenEnemies: [], defeatedEnemies: [] };
actor.enemies = [{ id: 'zenakado', kind: 'boss' }]; actor.saveProfile = () => {};
let checks = 0; actor.checkCollectionTitleUnlocks = () => checks++;
actor.noteEnemiesSeen();
assert(actor.hasMetEnemy('zenakado'), 'story encounter tracking remains available');
assert(actor.isArchiveHidden(actor.enemies[0]), 'encounter alone does not unlock encyclopedia');
assert.strictEqual(checks, 0, 'encounter cannot trigger collection title');
actor.rewardExpMultiplier = actor.rewardGoldMultiplier = () => 1;
actor.passiveEffectRate = actor.mealGoldBonusRate = () => 0;
actor.applyRewards = () => []; actor.grantJobExp = () => null; actor.updateHUD = () => {};
actor.grantEnemyReward({ id: 'zenakado', kind: 'boss', alive: false });
assert(!actor.isArchiveHidden(actor.enemies[0]), 'defeat unlocks encyclopedia');
assert.strictEqual(checks, 1, 'title is checked after defeat reward');
actor.grantEnemyReward({ id: 'zenakado', kind: 'boss', alive: false });
assert.strictEqual(actor.profile.defeatedEnemies.length, 1, 'no duplicate defeat entry');
actor.grantEnemyReward({ id: 'escaped', escaped: true });
assert(!actor.profile.defeatedEnemies.includes('escaped'));
console.log('archive defeat unlock regression: ok');
